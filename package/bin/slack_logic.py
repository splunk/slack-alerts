import json
import re
import ssl
from copy import deepcopy
from fnmatch import fnmatch
from urllib import error, request
from urllib.parse import quote, urlsplit

from safe_fmt import safe_format

SEVERITY_COLORS = ["#555555", "#6DB7C6", "#65A637", "#F7BC38", "#F58F39", "#D93F3C"]

OK = 0
ERROR_CODE_VALIDATION_FAILED = 2
ERROR_CODE_CHANNEL_NOT_FOUND = 3
ERROR_CODE_FORBIDDEN = 4
ERROR_CODE_HTTP_FAIL = 5
ERROR_CODE_UNEXPECTED = 6

DEFAULT_FROM_USER = "Splunk"
DEFAULT_FROM_USER_ICON = (
    "https://s3-us-west-1.amazonaws.com/ziegfried-apps/slack-alerts/splunk-icon.png"
)
FOOTER_ICON = (
    "https://s3-us-west-1.amazonaws.com/ziegfried-apps/slack-alerts/splunk-icon.png"
)

SECRET_KEY_MARKERS = ("token", "password", "secret", "webhook_url", "proxy_url")


def _is_secret_key(key):
    lowered = key.lower()
    return any(marker in lowered for marker in SECRET_KEY_MARKERS)


TEMPLATE_DEFAULTS = {
    "attachment_alert_title": ":bell: {search_name}",
    "attachment_adhoc_title": ":zap: Ad-hoc search",
    "attachment_results_link": "<{results_link}|Show results in Splunk> :mag:",
    "attachment_footer_text": "Splunk Alert",
    "attachment_fallback": "Alert generated by Splunk: {results_link}",
}


def _build_config(helper):
    config = {
        "channel": helper.get_param("channel"),
        "message": helper.get_param("message"),
        "attachment": helper.get_param("attachment") or "none",
        "fields": helper.get_param("fields"),
        "slack_app_oauth_token_override": helper.get_param(
            "slack_app_oauth_token_override"
        ),
        "proxy_url_override": helper.get_param("proxy_url_override"),
        "webhook_url_override": helper.get_param("webhook_url_override"),
        "slack_app_oauth_token": helper.get_global_setting("slack_app_oauth_token"),
        "webhook_url": helper.get_global_setting("webhook_url"),
        "from_user": helper.get_global_setting("from_user") or DEFAULT_FROM_USER,
        "from_user_icon": helper.get_global_setting("from_user_icon")
        or DEFAULT_FROM_USER_ICON,
    }
    config.update(TEMPLATE_DEFAULTS)

    settings = getattr(helper, "settings", None) or {}
    results_link = settings.get("results_link") or ""
    config["results_link"] = results_link

    view_link = helper.get_param("view_link")
    config["view_link"] = view_link if view_link else results_link

    trigger_time = helper.get_param("info_trigger_time")
    if trigger_time:
        config["info_trigger_time"] = trigger_time
    severity = helper.get_param("info_severity")
    if severity:
        config["info_severity"] = severity
    return config


def _proxy_uri(helper, config):
    override = config.get("proxy_url_override")
    if override:
        parts = urlsplit(override)
        if parts.scheme in ("http", "https") and parts.netloc:
            return override
        helper.log_error(
            "Ignoring malformed proxy_url_override; expected http(s)://host:port."
        )
        return ""
    proxy = helper.get_proxy() or {}
    if proxy.get("proxy_url") and proxy.get("proxy_port"):
        scheme = proxy.get("proxy_type") or "http"
        auth = ""
        if proxy.get("proxy_username"):
            auth = "%s:%s@" % (
                quote(proxy["proxy_username"], safe=""),
                quote(proxy.get("proxy_password", ""), safe=""),
            )
        return "%s://%s%s:%s" % (scheme, auth, proxy["proxy_url"], proxy["proxy_port"])
    return ""


def _format_template(template_key, config, payload, fallback=""):
    template = config.get(template_key)
    if template is not None:
        fallback = template
        try:
            args = deepcopy(payload)
            args["configuration"] = {
                k: ("****" if _is_secret_key(k) else v) for k, v in config.items()
            }
            return safe_format(template, args)
        except Exception:
            pass
    return fallback


def _build_fields_attachment(config, result):
    available_fields = list(result.keys())
    field_attachments = []
    seen_fields = set()
    field_list = re.split(r"\s*,\s*", (config.get("fields") or "").strip())
    for f in field_list:
        for af in available_fields:
            if af not in seen_fields and fnmatch(af, f):
                seen_fields.add(af)
                val = result[af]
                if isinstance(val, list):
                    val = val[0]
                field_attachments.append(dict(title=af, value=val, short=True))
    return field_attachments


def _build_alert_attachment(config, payload, result, search_name):
    attachment = dict()
    if config.get("info_severity") is not None:
        try:
            attachment["color"] = SEVERITY_COLORS[int(config["info_severity"])]
        except Exception:
            pass
    attachment["fallback"] = _format_template("attachment_fallback", config, payload)
    title_key = "attachment_alert_title" if search_name else "attachment_adhoc_title"
    attachment["title"] = _format_template(title_key, config, payload, "Alert")
    if config.get("attachment") == "message":
        attachment["text"] = _format_template("message", config, payload)
    else:
        attachment["text"] = _format_template(
            "attachment_results_link", config, payload
        )
    if config.get("view_link"):
        attachment["title_link"] = config.get("view_link")
    attachment["footer"] = _format_template("attachment_footer_text", config, payload)
    attachment["footer_icon"] = FOOTER_ICON
    if config.get("info_trigger_time"):
        try:
            attachment["ts"] = int(float(config.get("info_trigger_time")))
        except Exception:
            pass
    if config.get("fields"):
        attachment["fields"] = _build_fields_attachment(config, result)
    return attachment


def _build_slack_message(config, payload, result, search_name):
    params = dict()
    if config.get("attachment") != "message":
        params["text"] = _format_template("message", config, payload)
    if config.get("from_user"):
        params["username"] = config.get("from_user")
    if config.get("from_user_icon"):
        params["icon_url"] = config.get("from_user_icon")

    channel = config.get("channel")
    if channel:
        params["channel"] = channel

    if config.get("attachment", "none") != "none":
        params["attachments"] = [
            _build_alert_attachment(config, payload, result, search_name)
        ]
    elif config.get("fields"):
        params["attachments"] = [dict(fields=_build_fields_attachment(config, result))]
    return params


def _post(helper, url, data, headers, proxy_uri):
    opener = request.build_opener(
        (
            request.ProxyHandler({"http": proxy_uri, "https": proxy_uri})
            if proxy_uri
            else request.ProxyHandler({})
        ),
        request.HTTPSHandler(context=ssl.create_default_context()),
    )
    req = request.Request(url, data=data.encode("utf-8"), headers=headers)
    return opener.open(req)


def _send_slack_message(helper, config, message):
    body = json.dumps(message)
    proxy_uri = _proxy_uri(helper, config)

    token = config.get("slack_app_oauth_token_override") or config.get(
        "slack_app_oauth_token"
    )
    if token:
        url = "https://slack.com/api/chat.postMessage"
        headers = {
            "Content-Type": "application/json",
            "Authorization": "Bearer %s" % token,
        }
    else:
        url = config.get("webhook_url_override") or config.get("webhook_url") or ""
        if not url:
            helper.log_error("No Slack App OAuth token or webhook URL configured.")
            return ERROR_CODE_VALIDATION_FAILED
        if not url.startswith("https:"):
            helper.log_error("Invalid webhook URL specified. The URL must use HTTPS.")
            return ERROR_CODE_VALIDATION_FAILED
        headers = {"Content-Type": "application/json"}

    try:
        res = _post(helper, url, body, headers, proxy_uri)
        res_body = res.read().decode("utf-8", errors="replace")
        helper.log_info("Slack API responded with HTTP status=%d" % res.code)
        if 200 <= res.code < 300:
            if "invalid_auth" in res_body:
                helper.log_error(
                    "The Slack App OAuth token is invalid or lacks permission to post to the channel."
                )
                return ERROR_CODE_FORBIDDEN
            if "channel_not_found" in res_body or "channel_is_archived" in res_body:
                helper.log_error(
                    "The channel was not found or is archived. For private channels, add the Slack App to the channel."
                )
                return ERROR_CODE_CHANNEL_NOT_FOUND
            if '"error"' in res_body:
                helper.log_error("Slack API returned an error: %s" % res_body)
                return ERROR_CODE_HTTP_FAIL
            return OK
        helper.log_error(
            "Slack API returned HTTP status=%d body=%s" % (res.code, res_body)
        )
        return ERROR_CODE_HTTP_FAIL
    except error.HTTPError as e:
        helper.log_error("HTTP request to Slack API failed: %s" % e)
        try:
            res_body = e.read().decode("utf-8", errors="replace")
            if res_body in ("channel_not_found", "channel_is_archived"):
                return ERROR_CODE_CHANNEL_NOT_FOUND
            if res_body == "action_prohibited":
                return ERROR_CODE_FORBIDDEN
        except Exception:
            pass
        return ERROR_CODE_HTTP_FAIL


def process_event(helper, *args, **kwargs):
    try:
        try:
            helper.addinfo()
        except Exception:
            pass

        config = _build_config(helper)
        search_name = helper.search_name
        payload = {
            "configuration": dict(config),
            "search_name": search_name,
            "results_link": config.get("results_link", ""),
            "view_link": config.get("view_link", ""),
            "result": {},
        }

        events = list(helper.get_events())
        result = events[0] if events else {}
        payload["result"] = result

        message = _build_slack_message(config, payload, result, search_name)
        status = _send_slack_message(helper, config, message)
        if status == OK:
            helper.log_info("Successfully sent Slack message")
        else:
            helper.log_error("Slack alert action failed with code %d" % status)
        return status
    except Exception as e:
        helper.log_error("Unexpected error: %s" % e)
        return ERROR_CODE_UNEXPECTED
